// Explicit offline QA fixtures, never loaded into the normal desktop library.
import path from 'node:path';
import { mkdir, mkdtemp, writeFile, copyFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { DownloadScheduler } from '../dist/packages/core/src/fetcher/scheduler.js';
import { resolvePortableTools } from '../dist/packages/core/src/fetcher/config.js';
const base = path.resolve('artifacts/desktop');
await mkdir(base, { recursive: true });
const root = await mkdtemp(path.join(base, 'qa-'));
const dataDirectory = path.join(root, 'data');
const tools = resolvePortableTools(path.resolve('resources'));
const video = path.join(root, 'QA external video.mp4');
const cover = path.join(root, 'cover.png');
for (const args of [
  ['-f', 'lavfi', '-i', 'testsrc2=size=1280x720:rate=24', '-t', '2', '-c:v', 'libx264', '-preset', 'ultrafast', '-pix_fmt', 'yuv420p', video],
  ['-i', video, '-frames:v', '1', cover],
]) {
  const result = spawnSync(tools.ffmpeg, ['-hide_banner', '-loglevel', 'error', ...args], { windowsHide: true, shell: false, timeout: 20000 });
  if (result.status !== 0) throw new Error('Could not generate QA video');
}
const scheduler = await DownloadScheduler.create({ dataDirectory, tools }, async request => {
  await writeFile(path.join(request.cwd, 'media.info.json'), JSON.stringify({
    id: 'BaW_jenozKc', title: '离线验收素材｜本地视频挂载测试',
    description: '这是一份明确标记的离线验收素材，不是从 YouTube 下载的视频。用于检查桌面端读取已落盘的元数据、展示封面，以及通过原生文件选择器和文件拖入执行真实的 MP4 校验与复制。 Original description: local test pattern, generated by FFmpeg, with no external media download.',
    duration: 2, uploader: 'OmniPost QA', upload_date: '20261010', language: 'zh', tags: ['离线验收', '本地素材', 'MP4', '授权自制'], subtitles: { en: [] }
  }));
  await copyFile(cover, path.join(request.cwd, 'cover.png'));
  return { exitCode: 0, stderr: '' };
});
const tasks = [];
try { for (let i = 0; i < 2; i++) tasks.push(await scheduler.fetchMetadata('https://youtu.be/BaW_jenozKc')); }
finally { await scheduler.close(); }
if (tasks.some(task => task.state !== 'AWAITING_MEDIA')) throw new Error('QA metadata commit failed');
const result = { dataDirectory, video, taskIds: tasks.map(task => task.id) };
await writeFile(path.join(base, 'qa-fixture.json'), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
